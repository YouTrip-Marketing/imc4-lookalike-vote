/**
 * Bundles the Supabase Edge Function into one self-contained file.
 *
 *   npm run build:edge
 *
 * Writes supabase/functions/vote-api/index.js. The adapter imports code from
 * server/, src/domain/ and event.config.ts, which live outside
 * supabase/functions/. Whether Supabase's own bundler follows imports out of
 * that folder is not documented, so this removes the question: the output has
 * no imports at all.
 *
 * It does not deploy anything.
 */
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const ROOT = resolve(import.meta.dirname, '..');
export const EDGE_ENTRY = resolve(ROOT, 'server/adapters/supabase-edge.ts');
export const EDGE_OUTPUT = resolve(ROOT, 'supabase/functions/vote-api/index.js');

export async function buildEdgeFunction(outfile = EDGE_OUTPUT): Promise<string> {
  await build({
    entryPoints: [EDGE_ENTRY],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    legalComments: 'none',
    logLevel: 'silent',
    banner: {
      js: '// GENERATED by `npm run build:edge` from server/adapters/supabase-edge.ts. Do not edit.',
    },
  });
  return outfile;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const file = await buildEdgeFunction();
  console.log(`Wrote ${file}`);
  console.log('Nothing was deployed.');
}
